def latency_ms(m, warmup=5, runs=30):
    x = tf.constant(np.random.randint(0, 255, (1, 224, 224, 3)).astype("float32"))
    for _ in range(warmup): m(x, training=False)
    t = time.perf_counter()
    for _ in range(runs): m(x, training=False)
    return (time.perf_counter() - t) / runs * 1000

