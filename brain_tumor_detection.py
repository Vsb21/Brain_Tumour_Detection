for path in [MODEL_PATH, os.path.join(PROJECT, "common.py")]:
    if not os.path.isfile(path):
        raise FileNotFoundError(f"Missing file: {path}")

if not os.path.isdir(TEST_DIR):
    raise FileNotFoundError(f"Test dataset not found: {TEST_DIR}")

classes = list(CLASSES)
class_to_index = {str(c).lower(): i for i, c in enumerate(classes)}

# ==========================================
# LOAD TEST IMAGES
# ==========================================
extensions = (".jpg", ".jpeg", ".png", ".bmp", ".webp")
samples = []

for folder in sorted(os.listdir(TEST_DIR)):
    folder_path = os.path.join(TEST_DIR, folder)

    if not os.path.isdir(folder_path):
        continue

    if folder.lower() not in class_to_index:
        raise ValueError(
            f"Unknown test folder: {folder}. Expected: {classes}"
        )

    for filename in sorted(os.listdir(folder_path)):
        if filename.lower().endswith(extensions):
            samples.append((
                os.path.join(folder_path, filename),
                class_to_index[folder.lower()]
            ))

if not samples:
    raise RuntimeError("No test images found.")

