import os
import time
import numpy as np
import tensorflow as tf
import pandas as pd

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix
)

PROJECT = "/content/drive/MyDrive/BrainTumorProject"

MODEL_PATHS = {
    "ResNet-50": os.path.join(PROJECT, "resnet50.keras"),
    "Dilated CNN": os.path.join(PROJECT, "dilated_cnn.keras")
}

TEST_DIR = os.path.join(PROJECT, "Testing")
IMG_SIZE = (224, 224)
BATCH_SIZE = 32

# Load test images
test_ds = tf.keras.utils.image_dataset_from_directory(
    TEST_DIR,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    shuffle=False
)

class_names = test_ds.class_names
y_true = np.concatenate([y.numpy() for x, y in test_ds])

# Normalize images if the models expect pixel values in [0, 1]
test_ds = test_ds.map(
    lambda x, y: (tf.cast(x, tf.float32) / 255.0, y)
)

results = []

for name, path in MODEL_PATHS.items():
    print(f"\n{'=' * 55}")
    print(f"BENCHMARK: {name}")
    print("=" * 55)

    if not os.path.exists(path):
        print("Model file not found:", path)
        continue

    model = tf.keras.models.load_model(path, compile=False)

    # Warm-up
    for images, _ in test_ds.take(1):
        model(images, training=False)

    y_pred_probs = []
    start = time.perf_counter()

    for images, _ in test_ds:
        predictions = model(images, training=False)
        y_pred_probs.append(predictions.numpy())

    elapsed = time.perf_counter() - start

    probs = np.concatenate(y_pred_probs)

    # Supports standard softmax/sigmoid classifiers
    if probs.ndim == 2 and probs.shape[1] > 1:
        y_pred = np.argmax(probs, axis=1)
    else:
        y_pred = (probs.reshape(-1) >= 0.5).astype(int)

    accuracy = accuracy_score(y_true, y_pred)
    precision = precision_score(
        y_true, y_pred, average="macro", zero_division=0
    )
    recall = recall_score(
        y_true, y_pred, average="macro", zero_division=0
    )
    f1 = f1_score(
        y_true, y_pred, average="macro", zero_division=0
    )

    total_images = len(y_true)
    avg_latency_ms = elapsed * 1000 / total_images
    throughput = total_images / elapsed

    results.append({
        "Model": name,
        "Accuracy (%)": accuracy * 100,
        "Precision (%)": precision * 100,
        "Recall (%)": recall * 100,
        "F1-score (%)": f1 * 100,
        "Avg inference (ms/image)": avg_latency_ms,
        "Throughput (images/sec)": throughput,
        "Parameters": model.count_params()
    })

    print(f"Test images: {total_images}")
    print(f"Accuracy: {accuracy * 100:.2f}%")
    print(f"Precision (macro): {precision * 100:.2f}%")
    print(f"Recall (macro): {recall * 100:.2f}%")
    print(f"F1-score (macro): {f1 * 100:.2f}%")
    print(f"Average inference: {avg_latency_ms:.2f} ms/image")
    print(f"Throughput: {throughput:.2f} images/sec")
    print(f"Parameters: {model.count_params():,}")

    print("\nClassification Report:")
    print(classification_report(
        y_true, y_pred,
        labels=range(len(class_names)),
        target_names=class_names,
        zero_division=0
    ))

    print("Confusion Matrix:")
    print(confusion_matrix(
        y_true, y_pred,
        labels=range(len(class_names))
    ))

    del model
    tf.keras.backend.clear_session()

print("\n" + "=" * 70)
print("FINAL MODEL BENCHMARK COMPARISON")
print("=" * 70)

if results:
    benchmark_df = pd.DataFrame(results)
    print(benchmark_df.round(2).to_string(index=False))
else:
    print("No models were benchmarked. Check the model paths.")

