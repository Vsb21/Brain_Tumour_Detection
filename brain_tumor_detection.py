    result = analyze(image, model, fm, ood)
    elapsed = time.perf_counter() - start

    probs = np.asarray(result["probs"], dtype=float).reshape(-1)

    if len(probs) != len(classes):
        raise ValueError(
            f"Expected {len(classes)} class probabilities, got {len(probs)}"
        )

    if not np.all(np.isfinite(probs)):
        raise ValueError(f"Invalid model output for {image_path}")

    y_probs.append(probs)
    latencies.append(elapsed)

    if result.get("status") == "rejected":
        rejected += 1

    if i % 100 == 0 or i == len(samples):
        print(f"Processed {i}/{len(samples)}")

